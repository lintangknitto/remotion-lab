/**
 * Scan public/library, build the asset index, and detect duplicates.
 *
 *   node scripts/scan-library.mjs
 *
 * Writes:
 *   src/library/index.generated.json  (id -> path, hash, size, dims/duration)
 *   src/library/ids.ts                (AssetId union type)
 *
 * A file's id IS its filename without the extension, e.g.
 *   public/library/sfx/sfx.impact.heavy-01.wav  ->  "sfx.impact.heavy-01"
 * That makes the id stable even if the file moves to another subfolder.
 */

import {createHash} from 'node:crypto';
import {readdir, readFile, stat, writeFile, mkdir} from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';

const ROOT = path.resolve(import.meta.dirname, '..');
const LIB = path.join(ROOT, 'public', 'library');
const OUT_JSON = path.join(ROOT, 'src', 'library', 'index.generated.json');
const OUT_TS = path.join(ROOT, 'src', 'library', 'ids.ts');

const EXTS = new Set(['.png', '.jpg', '.jpeg', '.webp', '.wav', '.mp3', '.m4a', '.mp4', '.webm', '.mov', '.gif']);
const ID_RE = /^[a-z][a-z0-9-]*(\.[a-z0-9-]+)+$/;

async function walk(dir) {
  const entries = await readdir(dir, {withFileTypes: true});
  const files = [];
  for (const e of entries) {
    const full = path.join(dir, e.name);
    if (e.isDirectory()) files.push(...(await walk(full)));
    else files.push(full);
  }
  return files;
}

function wavDuration(buf) {
  if (buf.toString('ascii', 0, 4) !== 'RIFF') return null;
  let off = 12;
  let byteRate = 0;
  let dataSize = 0;
  while (off + 8 <= buf.length) {
    const id = buf.toString('ascii', off, off + 4);
    const size = buf.readUInt32LE(off + 4);
    if (id === 'fmt ') byteRate = buf.readUInt32LE(off + 16);
    if (id === 'data') {
      dataSize = size;
      break;
    }
    off += 8 + size + (size % 2);
  }
  return byteRate ? +(dataSize / byteRate).toFixed(3) : null;
}

function pngSize(buf) {
  if (buf.toString('ascii', 1, 4) !== 'PNG') return null;
  return {width: buf.readUInt32BE(16), height: buf.readUInt32BE(20)};
}

const hash = (buf) => createHash('sha256').update(buf).digest('hex');

async function main() {
  let files;
  try {
    files = await walk(LIB);
  } catch {
    console.error(`no library at ${path.relative(ROOT, LIB)} — run scripts/assets/generate.py first`);
    process.exit(1);
  }

  const assets = [];
  const byHash = new Map();
  const problems = [];

  for (const file of files.sort()) {
    const rel = path.relative(LIB, file).split(path.sep).join('/');
    const base = path.basename(file);
    const ext = path.extname(base).toLowerCase();
    if (!EXTS.has(ext)) continue;

    const id = base.slice(0, -ext.length);
    if (!ID_RE.test(id)) {
      problems.push(`bad filename "${rel}" — expected <type>.<sub>.<name>-<nn>.<ext>`);
      continue;
    }

    const buf = await readFile(file);
    const h = hash(buf);
    const parts = id.split('.');

    if (byHash.has(h)) {
      problems.push(`duplicate content: "${id}" == "${byHash.get(h)}" (same sha256) — keep one and reference it`);
    } else {
      byHash.set(h, id);
    }

    const meta = {
      id,
      type: parts[0],
      sub: parts[1],
      path: `library/${rel}`,
      ext,
      bytes: buf.length,
      sha256: h.slice(0, 16),
    };
    if (ext === '.wav') meta.durationSec = wavDuration(buf);
    if (ext === '.png') Object.assign(meta, pngSize(buf) ?? {});
    assets.push(meta);
  }

  const totalBytes = assets.reduce((a, b) => a + b.bytes, 0);
  const byType = assets.reduce((acc, a) => {
    acc[a.type] = (acc[a.type] ?? 0) + 1;
    return acc;
  }, {});

  const payload = {
    generatedAt: new Date().toISOString(),
    root: 'public/library',
    count: assets.length,
    totalBytes,
    byType,
    assets,
  };

  await mkdir(path.dirname(OUT_JSON), {recursive: true});
  await writeFile(OUT_JSON, JSON.stringify(payload, null, 2) + '\n');

  const ids = assets.map((a) => a.id).sort();
  const ts = `// AUTO-GENERATED by scripts/scan-library.mjs — do not edit by hand.
// ${assets.length} assets, ${(totalBytes / 1024 / 1024).toFixed(1)} MB.

export type AssetId =
${ids.map((id) => `  | '${id}'`).join('\n')};

export const ASSET_IDS: AssetId[] = [
${ids.map((id) => `  '${id}',`).join('\n')}
];
`;
  await writeFile(OUT_TS, ts);

  console.log(`scanned ${assets.length} assets  ${(totalBytes / 1024 / 1024).toFixed(1)} MB`);
  console.log(
    'by type: ' +
      Object.entries(byType)
        .map(([k, v]) => `${k}=${v}`)
        .join('  '),
  );
  console.log(`wrote ${path.relative(ROOT, OUT_JSON)}`);
  console.log(`wrote ${path.relative(ROOT, OUT_TS)}`);

  if (problems.length) {
    console.error(`\n${problems.length} problem(s):`);
    for (const p of problems) console.error('  - ' + p);
    process.exit(1);
  }
}

await main();
